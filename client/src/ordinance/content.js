// 자료 이름: "자료 1 통계 · 소음 민원 통계" 처럼 표시
export function materialTitle(track, key) {
  const k = MATERIAL_KIND[key];
  const m = track?.materials?.[key];
  if (key === 'm1' && m?.title) return `${k.no} ${k.kind} · ${m.title}`;
  if ((key === 'm2' || key === 'm3') && m?.speaker) return `${k.no} ${k.kind} · ${m.speaker}`;
  return `${k.no} ${k.kind}`;
}

